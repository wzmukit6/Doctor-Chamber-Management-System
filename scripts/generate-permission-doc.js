#!/usr/bin/env node
/**
 * Regenerates docs/PERMISSIONS.md from the single source of truth in
 * packages/shared (run `npm run build:shared` first).
 */
const fs = require('node:fs');
const path = require('node:path');
const { PERMISSION_GROUPS, DEFAULT_ROLE_PERMISSIONS, FORBIDDEN_GRANTS, ROLE_KEYS, MANAGEABLE_ROLES } = require('../packages/shared/dist');
const en = require('../apps/web/src/i18n/locales/en.json');

const roles = ROLE_KEYS;
const cell = (role, p) => (DEFAULT_ROLE_PERMISSIONS[role].includes(p) ? '✅' : FORBIDDEN_GRANTS[role].includes(p) ? '🔒' : '—');

let md = `# Permission matrix

> Generated by \`scripts/generate-permission-doc.js\` from \`packages/shared/src/permissions.ts\`. Do not edit by hand.

Authorization = **role + permission + tenant scope (chamber) + resource ownership + resource state**.
The table shows the *default* grants. A Super Admin can reconfigure grants at runtime
(Roles & permissions screen, always audited with a reason) **except** 🔒 cells, which the API
refuses for that role no matter who asks.

Legend: ✅ granted by default · — not granted (can be enabled) · 🔒 can never be granted

`;
for (const g of PERMISSION_GROUPS) {
  md += `\n## ${en.permissions.groups[g.key]}\n\n| Permission | Key | ${roles.map((r) => en.roles[r]).join(' | ')} |\n|---|---|${roles.map(() => ':-:').join('|')}|\n`;
  for (const p of g.permissions) {
    md += `| ${en.permissions.labels[p]} | \`${p}\` | ${roles.map((r) => cell(r, p)).join(' | ')} |\n`;
  }
}

md += `\n## Who can manage whom\n\n| Actor | Can create / manage accounts with role |\n|---|---|\n`;
for (const r of roles) md += `| ${en.roles[r]} | ${MANAGEABLE_ROLES[r].map((x) => en.roles[x]).join(', ') || '—'} |\n`;

md += `
## Scope rules enforced in services (beyond permissions)

| Rule | Where |
|---|---|
| Chamber-scoped users only see rows of their active chamber; other chambers' records are reported as **404** (no existence leak). | \`AuthorizationService.chamberScope / assertChamberAccess\` |
| Managers toggle a user's **membership** in their chamber, never the global identity; a global password reset requires authority over every chamber the user belongs to. | \`UsersService\` |
| Only a Super Admin can activate/deactivate a chamber. | \`ChambersService.update\` |
| Users cannot deactivate, delete or admin-reset themselves. | \`UsersService\` |
| Audit logs: Super Admin → all; Manager → own chamber; Doctor → own actions. IP/device only shown to Super Admin & Manager. No endpoint can modify audit rows; the database blocks UPDATE/DELETE. | \`AuditController\`, DB trigger |
| Super Admin role always holds every permission and cannot be edited. | \`RolesService\` |
| Patients are registered in, and only visible to, the actor's active chamber; a platform admin without a chamber cannot register patients. | \`PatientsService\` |
| Capturing medical history or allergies at registration additionally requires \`patients.update_medical\`. | \`PatientsService.create\` |
| Only the appointment's doctor can start, complete or return a consultation, and a doctor can only call patients from their own queue (\`NOT_APPOINTMENT_DOCTOR\`). | \`AppointmentsService.act\`, \`QueueService\` |
| Appointment actions follow an explicit status machine; each action additionally requires its own permission (e.g. check-in → \`queue.manage\`, start → \`consultations.create\`, cancel → \`appointments.cancel\` + reason). | \`AppointmentsService.act\` |
| Only the consultation's doctor can edit, finalize, cancel or add addenda (\`NOT_CONSULTATION_DOCTOR\`); finalized consultations are immutable (API + database triggers). | \`ConsultationsService\`, DB triggers |
| Private clinical notes are returned only with \`clinical_notes.view\`; the patient context (allergies, conditions) only with \`patients.view_medical\`. | \`ConsultationsService\` |
| Global catalogue entries and vital fields are changed only with \`system.manage\`; chamber entries only by that chamber. | \`CatalogService\`, \`VitalDefinitionsService\` |
| Medical values in audit logs and the patient timeline are redacted for viewers without \`patients.view_medical\`. | \`AuditController\`, \`PatientTimelineService\` |
| Only the prescribing doctor can revise, finalize or discard a revision (\`NOT_PRESCRIPTION_DOCTOR\`); issued prescription versions are immutable (API + database triggers). | \`PrescriptionsService\`, DB triggers |
| Users without \`prescriptions.create\` (assistants, managers) only see issued prescriptions — never drafts or cancelled ones. | \`PrescriptionsService\` |
| Global medicines are changed only with \`medicines.manage_global\`; deactivating a medicine additionally needs \`medicines.delete\`. | \`MedicinesService\` |
| Personal templates are visible only to their doctor; shared templates to the whole chamber. | \`TemplatesService\` |
| The public verification endpoint returns no patient data and is rate limited. | \`PublicPrescriptionsController\` |
`;

fs.writeFileSync(path.join(__dirname, '..', 'docs', 'PERMISSIONS.md'), md);
console.log('docs/PERMISSIONS.md written');
